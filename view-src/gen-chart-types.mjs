// Generates src/chart_creator/chart_types.py from Flint's own template definitions,
// so the Python config enums and the LLM prompt catalog never drift from the
// installed flint-chart version. Run via `npm run gen`.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import {
  vlAllTemplateDefs,
  ecAllTemplateDefs,
  cjsAllTemplateDefs,
} from "flint-chart";

const here = dirname(fileURLToPath(import.meta.url));
const outPy = resolve(here, "../src/chart_creator/chart_types.py");

// Collapse a backend's template defs to unique chart names (in first-seen order)
// with the union of the channels each chart can encode.
function collect(defs) {
  const byName = new Map();
  for (const d of defs) {
    const name = d.chart;
    if (!name) continue;
    const prev = byName.get(name) || new Set();
    for (const ch of d.channels || []) prev.add(ch);
    byName.set(name, prev);
  }
  return [...byName.entries()].map(([chart, channels]) => ({
    chart,
    channels: [...channels],
  }));
}

const backends = {
  "vega-lite": collect(vlAllTemplateDefs),
  echarts: collect(ecAllTemplateDefs),
  chartjs: collect(cjsAllTemplateDefs),
};

const CONST = { "vega-lite": "VEGA_LITE_TYPES", echarts: "ECHARTS_TYPES", chartjs: "CHARTJS_TYPES" };

const pyLines = [];
pyLines.push('"""AUTO-GENERATED by view-src/gen-chart-types.mjs — do not edit by hand.');
pyLines.push("");
pyLines.push("Chart-type catalog derived from flint-chart's own template definitions so the");
pyLines.push("config enums and the LLM prompt stay in sync with the installed Flint version.");
pyLines.push('Regenerate with: cd view-src && npm run gen"""');
pyLines.push("");
pyLines.push("from __future__ import annotations");
pyLines.push("");

for (const [lib, items] of Object.entries(backends)) {
  pyLines.push(`${CONST[lib]} = (`);
  for (const it of items) pyLines.push(`    ${JSON.stringify(it.chart)},`);
  pyLines.push(")");
  pyLines.push("");
}

pyLines.push("CHART_TYPES_BY_LIBRARY = {");
pyLines.push('    "vega-lite": VEGA_LITE_TYPES,');
pyLines.push('    "echarts": ECHARTS_TYPES,');
pyLines.push('    "chartjs": CHARTJS_TYPES,');
pyLines.push("}");
pyLines.push("");

// A compact markdown catalog (name + encoding channels) for the LLM prompt.
const catalog = [];
const LABEL = { "vega-lite": "Vega-Lite", echarts: "ECharts", chartjs: "Chart.js" };
for (const [lib, items] of Object.entries(backends)) {
  catalog.push(`### ${LABEL[lib]} (library: "${lib}")`);
  for (const it of items) {
    const ch = it.channels.length ? ` — channels: ${it.channels.join(", ")}` : "";
    catalog.push(`- ${it.chart}${ch}`);
  }
  catalog.push("");
}
const catalogStr = catalog.join("\n");
pyLines.push("CHART_CATALOG_MARKDOWN = r'''" + catalogStr + "'''");
pyLines.push("");

writeFileSync(outPy, pyLines.join("\n"));
console.log(`Wrote ${outPy}`);
for (const [lib, items] of Object.entries(backends)) {
  console.log(`  ${lib}: ${items.length} chart types`);
}
